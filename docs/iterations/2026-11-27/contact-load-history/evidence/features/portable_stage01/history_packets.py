"""Compact I-64 NumPy replay against exact canonical array bindings.

Original cached primitives and metadata are copied unchanged. Large derived
history NPZs stay local; their arrays are regenerated and checked by byte hash.
No values are substituted, normalized, encoded or approximated.
"""
from pathlib import Path
from datetime import datetime,timezone
import argparse,hashlib,importlib.util,json,shutil,sys
import numpy as np

CASES=('m100_B','p030_B','p090_B')


def sha(path):return hashlib.sha256(Path(path).read_bytes()).hexdigest()
def read(path):return json.loads(Path(path).read_text())
def write(path,value):Path(path).write_text(json.dumps(value,indent=2,allow_nan=False)+'\n')
def load(path):
    with np.load(path,allow_pickle=False) as value:return {key:value[key].copy() for key in value.files}
def description(value):return dict(dtype=str(value.dtype),shape=list(value.shape),sha256=hashlib.sha256(value.tobytes()).hexdigest())
def helper(path):
    spec=importlib.util.spec_from_file_location('_i64_cached_history_helper',path);module=importlib.util.module_from_spec(spec);spec.loader.exec_module(module);return module
def verify_original(directory):
    for item in read(directory/'artifact_manifest.json')['files']:
        if sha(directory/item['path'])!=item['sha256']:raise ValueError('Changed original feature artifact: '+item['path'])


def load_and_derive_case(package,case):
    """Return freshly derived full-rate arrays and strict array-binding parity."""
    package=Path(package);manifest=read(package/'packet_manifest.json')
    if case not in CASES:raise ValueError('Unregistered case')
    if sha(Path(__file__))!=manifest['replay_source_sha256']:raise ValueError('Changed portable replay source')
    entry=manifest['cases'][case];directory=package/case
    binding_path=directory/'array_bindings.json'
    if sha(binding_path)!=entry['array_bindings_sha256']:raise ValueError('Changed canonical array binding')
    bindings=read(binding_path)
    for item in bindings['retained_files']:
        if sha(directory/item['path'])!=item['sha256']:raise ValueError('Changed required portable input: '+item['path'])
    original=read(directory/'original_artifact_manifest.json')
    original_derived=[item for item in original['files'] if item['path']=='history_features.npz']
    if len(original_derived)!=1 or original_derived[0]['sha256']!=bindings['omitted_derived_file']['sha256']:raise ValueError('Canonical derived-file provenance differs')
    primitives=load(directory/'primitives.npz')
    primitive_fields={key:description(value) for key,value in primitives.items()}
    if primitive_fields!=bindings['primitive_fields']:raise ValueError('Portable primitive bytes differ')
    derived=helper(directory/'source/history_features.py').derive_history(primitives)
    if set(derived)!=set(bindings['derived_fields']):raise ValueError('Derived array fields differ')
    fields={key:dict(byte_exact=description(value)==bindings['derived_fields'][key],
        actual=description(value),expected=bindings['derived_fields'][key]) for key,value in derived.items()}
    parity=dict(case=case,numpy_version=np.__version__,array_count=len(fields),
        all_byte_exact=all(row['byte_exact'] for row in fields.values()),fields=fields,
        cached_geometry_not_regenerated=True,no_reported_values_replaced=True,
        original_derived_file_omitted=True,original_derived_file_sha256=bindings['omitted_derived_file']['sha256'])
    return derived,parity


def prepare(source_root,output):
    output.mkdir(parents=True,exist_ok=False)
    write(output/'registered_before_binding_generation.json',dict(registered_utc=datetime.now(timezone.utc).isoformat(),
        source_sha256=sha(Path(__file__)),numpy_version=np.__version__,
        original_manifests={case:sha(source_root/case/'artifact_manifest.json') for case in CASES},
        scope='Copy original primitives/metadata/source; bind canonical derived array bytes; do not alter scientific formulas or data.'))
    shutil.copy2(Path(__file__),output/'history_packets.py');entries={}
    for case in CASES:
        original=source_root/case;verify_original(original);directory=output/case;directory.mkdir()
        source_manifest=read(original/'artifact_manifest.json');retained=[];omitted=None
        for item in source_manifest['files']:
            if item['path']=='history_features.npz':omitted=dict(item,reason='Exact derived arrays regenerated by frozen NumPy source and checked against per-array bindings.');continue
            target=directory/item['path'];target.parent.mkdir(parents=True,exist_ok=True)
            shutil.copy2(original/item['path'],target);retained.append(item)
        if omitted is None:raise ValueError('Missing canonical derived provenance')
        shutil.copy2(original/'artifact_manifest.json',directory/'original_artifact_manifest.json')
        retained.append(dict(path='original_artifact_manifest.json',sha256=sha(directory/'original_artifact_manifest.json'),bytes=(directory/'original_artifact_manifest.json').stat().st_size))
        primitives=load(original/'primitives.npz');derived=load(original/'history_features.npz')
        write(directory/'array_bindings.json',dict(iteration='I-64',case=case,producer_numpy=np.__version__,
            original_artifact_manifest_sha256=sha(original/'artifact_manifest.json'),retained_files=retained,
            omitted_derived_file=omitted,primitive_fields={key:description(value) for key,value in primitives.items()},
            derived_fields={key:description(value) for key,value in derived.items()}))
        entries[case]=dict(array_bindings_sha256=sha(directory/'array_bindings.json'),
            primitive_bytes=(directory/'primitives.npz').stat().st_size,derived_array_count=len(derived))
        verify_original(original)
    write(output/'packet_manifest.json',dict(iteration='I-64',replay_source_sha256=sha(Path(__file__)),
        producer_numpy=np.__version__,cases=entries,omission='Only history_features.npz is omitted; its byte identity is bound in original manifest and per-array hashes.'))
    checks={case:load_and_derive_case(output,case)[1] for case in CASES};write(output/'producer_parity.json',checks)
    if not all(row['all_byte_exact'] for row in checks.values()):raise ValueError('Producer derived-array replay differs')
    print(json.dumps(dict(passed=True,numpy_version=np.__version__,array_count=sum(row['array_count'] for row in checks.values()),
        primitive_bytes=sum(row['primitive_bytes'] for row in entries.values()))),flush=True)


def check(package,output):
    output.mkdir(parents=True,exist_ok=False)
    write(output/'registered_before_replay.json',dict(registered_utc=datetime.now(timezone.utc).isoformat(),
        source_sha256=sha(Path(__file__)),packet_manifest_sha256=sha(package/'packet_manifest.json'),numpy_version=np.__version__,
        comparison='Strict array metadata/byte hashes; no tolerance, replacement or normalization.'))
    checks={case:load_and_derive_case(package,case)[1] for case in CASES};write(output/'replay_report.json',checks)
    passed=all(row['all_byte_exact'] for row in checks.values())
    print(json.dumps(dict(passed=passed,numpy_version=np.__version__,array_count=sum(row['array_count'] for row in checks.values()))))
    return 0 if passed else 1


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__);sub=parser.add_subparsers(dest='mode',required=True)
    build=sub.add_parser('prepare');build.add_argument('--source-root',type=Path,required=True);build.add_argument('--output',type=Path,required=True)
    replay=sub.add_parser('check');replay.add_argument('--package',type=Path,required=True);replay.add_argument('--output',type=Path,required=True)
    args=parser.parse_args()
    if args.mode=='prepare':prepare(args.source_root.resolve(),args.output.resolve())
    else:sys.exit(check(args.package.resolve(),args.output.resolve()))
