"""Strict NumPy-only I-63 causal-feature replay from original cached primitives.

Model patch axes are cached inputs, not regenerated by this replay. No MuJoCo,
ROS, original robot logs, contact truth or candidate scores are needed.
"""
from pathlib import Path
from datetime import datetime,timezone
import argparse,hashlib,importlib.util,json,sys
import numpy as np

CASES=('m100_B','p030_B','p090_B')


def sha(path):return hashlib.sha256(Path(path).read_bytes()).hexdigest()
def read(path):return json.loads(Path(path).read_text())
def write(path,value):Path(path).write_text(json.dumps(value,indent=2,allow_nan=False)+'\n')
def load(path):
    with np.load(path,allow_pickle=False) as value:return {key:value[key].copy() for key in value.files}
def description(value):
    return dict(dtype=str(value.dtype),shape=list(value.shape),sha256=hashlib.sha256(value.tobytes()).hexdigest())
def helper(path):
    spec=importlib.util.spec_from_file_location('_i63_cached_condition_helper',path);module=importlib.util.module_from_spec(spec);spec.loader.exec_module(module);return module


def verify_artifacts(directory):
    manifest=read(directory/'artifact_manifest.json')
    for item in manifest['files']:
        if sha(directory/item['path'])!=item['sha256']:raise ValueError('Changed original feature artifact: '+item['path'])


def load_and_derive_case(features_root,case):
    """Return (all full-rate derived arrays, explicit strict byte-parity report).

    ``features_root`` contains CASE/primitives.npz, conditions.npz, source/ and
    artifact_manifest.json. The returned arrays are freshly computed values;
    the function never substitutes stored reference values or normalizes them.
    """
    if case not in CASES:raise ValueError('Unknown case')
    directory=Path(features_root)/case;verify_artifacts(directory)
    primitives=load(directory/'primitives.npz');reference=load(directory/'conditions.npz')
    source=directory/'source/condition_features.py';derived=helper(source).derive_features(primitives)
    if set(derived)!=set(reference):raise ValueError('Derived feature fields differ from canonical reference')
    fields={}
    for key,value in derived.items():
        expected=reference[key];actual_metadata=description(value);reference_metadata=description(expected)
        row=dict(byte_exact=actual_metadata==reference_metadata,expected=reference_metadata,actual=actual_metadata)
        if value.shape==expected.shape and np.issubdtype(value.dtype,np.floating) and not row['byte_exact']:
            finite=np.isfinite(value)&np.isfinite(expected)
            row['finite_max_absolute_difference']=float(np.max(np.abs(value[finite]-expected[finite]))) if finite.any() else None
            row['finite_patterns_exact']=bool(np.array_equal(np.isfinite(value),np.isfinite(expected)))
        fields[key]=row
    verify_artifacts(directory)
    parity=dict(case=case,numpy_version=np.__version__,feature_source_sha256=sha(source),
        original_artifact_manifest_sha256=sha(directory/'artifact_manifest.json'),
        primitive_sha256=sha(directory/'primitives.npz'),array_count=len(fields),
        all_byte_exact=all(row['byte_exact'] for row in fields.values()),fields=fields,
        no_values_replaced=True,no_kinematic_regeneration=True,no_new_physics=True)
    return derived,parity


def main(features_root,output):
    output.mkdir(parents=True,exist_ok=False)
    write(output/'registered_before_replay.json',dict(replay_source_sha256=sha(Path(__file__)),numpy_version=np.__version__,
        manifests={case:sha(features_root/case/'artifact_manifest.json') for case in CASES},
        registered_utc=datetime.now(timezone.utc).isoformat(),comparison='Strict byte comparison; no normalization, tolerance or replacement.'))
    checks={}
    for case in CASES:
        values,parity=load_and_derive_case(features_root,case);checks[case]=parity
        np.savez_compressed(output/(case+'_conditions.npz'),**values)
    write(output/'replay_report.json',checks)
    passed=all(row['all_byte_exact'] for row in checks.values())
    print(json.dumps(dict(passed=passed,numpy_version=np.__version__,array_count=sum(row['array_count'] for row in checks.values()))))
    return 0 if passed else 1


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--features-root',type=Path,required=True)
    parser.add_argument('--output',type=Path,required=True);args=parser.parse_args()
    sys.exit(main(args.features_root.resolve(),args.output.resolve()))
